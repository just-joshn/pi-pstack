"""Generate the catalog and parity listings from the upstream map and the ported files.

Inputs:  src/reference/source-map.json (upstream graph; change it only to follow upstream)
         scripts/catalog-source.json (Pi implementation classifications and paths)
         src/skills/poteto-mode/playbooks/*.md (each playbook's numbered steps)
Outputs: src/lib/catalog-data.json, src/reference/parity.json, src/reference/PARITY.md

The skills, playbooks and agents under src/ are ported by hand from upstream pstack and Team Kit;
this script never writes them. Catalog paths are relative to src/.

Run `python3 scripts/generate.py` to refresh the outputs, or add `--check` to check them.
"""

import argparse
import json
import re
import subprocess
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
PACKAGED = ROOT / "src"
PLAYBOOKS = PACKAGED / "skills/poteto-mode/playbooks"
GENERATED_BY = "scripts/generate.py"
MARKER = (
    f"<!-- Generated by {GENERATED_BY} from scripts/catalog-source.json. "
    "Edit the source, then run `python3 scripts/generate.py`. -->"
)
STATUS_DEFINITIONS = {
    "extension": "Executable Pi extension integration; live verification pending",
    "instruction": "Native skill or playbook; model-mediated, not deterministic",
    "host": "Provided by Pi",
    "conditional": "Requires project tool, external service, credentials, or workflow validation",
    "gap": "Managed service has no native equivalent",
    "navigation": "Native terminal catalog navigation",
}

upstream = json.loads((PACKAGED / "reference/source-map.json").read_text())
source = json.loads((ROOT / "scripts/catalog-source.json").read_text())


def first_sentence(line):
    text = re.sub(r"^\d+\.\s+", "", line).replace("**", "").strip()
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    return match.group(1) if match else text


def playbook_steps(path):
    lines = path.read_text().splitlines()
    numbered = [first_sentence(line) for line in lines if re.match(r"\d+\.\s", line)]
    return numbered or [lines[0].lstrip("# ").strip()]


def apply_overrides(base, overrides):
    merged = list(base)
    for line in overrides:
        number = int(re.search(r"step (\d+)", line).group(1))
        task = first_sentence(line)
        at = merged.index(base[number - 1])
        if task.startswith(f"In place of step {number}"):
            merged[at] = task
        else:
            merged.insert(at + 1, task)
    return merged


def playbook_plan(path, own):
    lines = path.read_text().splitlines()
    parent = re.match(r"Run the (\S+) playbook", lines[2])
    if not parent:
        return own[path.stem]
    overrides = [line for line in lines if re.match(r"\d+\.\s", line)]
    return apply_overrides(own[parent.group(1).lower()], overrides)


playbooks = sorted(PLAYBOOKS.glob("*.md"))
own_steps = {path.stem: playbook_steps(path) for path in playbooks}
steps = {path.stem: playbook_plan(path, own_steps) for path in playbooks}


def is_skill(node):
    return node["kind"] == "public" or (
        node["id"].startswith("kit-") and node["label"].startswith("/")
    )


def classify(node):
    node_id = node["id"]
    if is_skill(node):
        name = node["label"].lstrip("/")
        path = f"skills/{name}/SKILL.md"
        if node_id in source["extensionSkills"]:
            status = "extension"
        elif node_id in source["conditionalSkills"]:
            status = "conditional"
        else:
            status = "instruction"
        command = "" if node_id.startswith("principle-") else f"; /{name}"
        return status, path + command, path, f"/skill:{name}"
    route = node_id.removeprefix("pb-")
    if node_id.startswith("pb-") and route in steps:
        path = f"skills/poteto-mode/playbooks/{route}.md"
        status = (
            "conditional" if route in source["conditionalPlaybooks"] else "instruction"
        )
        return status, f"{path} + pstack_plan", path, f"/pstack-run {route}"
    if "navigation group" in node["how"]:
        return "navigation", f"/pstack-map {node['opensView']}", None, None
    status, implementation = source["implementations"][node_id]
    return status, implementation, None, None


def json_text(value):
    return json.dumps(value, indent=2) + "\n"


def reconcile(outputs, check):
    stale = []
    with TemporaryDirectory(prefix="pstack-generate-") as tmp:
        stage = Path(tmp)
        for path, content in outputs.items():
            target = stage / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
        config = f"--config={ROOT / 'bunfig.toml'}"
        subprocess.run(
            ["bun", config, "fmt", "--log-level=warn", *outputs], cwd=stage, check=True
        )
        for path in outputs:
            expected = (stage / path).read_bytes()
            target = PACKAGED / path
            if target.is_file() and target.read_bytes() == expected:
                continue
            stale.append(target.relative_to(ROOT).as_posix())
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(expected)
    if check and stale:
        raise SystemExit(
            "Stale generated files; run `python3 scripts/generate.py`:\n"
            + "\n".join(sorted(stale))
        )


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="check generated files without writing")
args = parser.parse_args()
paths, implementations, matrix = dict(source["instructionPaths"]), {}, []
for node in upstream["nodes"]:
    status, implementation, path, invocation = classify(node)
    implementations[node["id"]] = (status, implementation)
    matrix.append(
        {
            "id": node["id"],
            "kind": node["kind"],
            "status": status,
            "implementation": implementation,
            "invocation": invocation,
            "source": node["source"],
        }
    )
    if path:
        paths[node["id"]] = path

rows = "".join(
    f"| `{row['id']}` | {row['status']} | {row['implementation'].replace('|', ' or ')} |\n"
    for row in matrix
)
outputs = {
    "lib/catalog-data.json": json_text(
        {
            "generatedBy": GENERATED_BY,
            "paths": paths,
            "steps": steps,
            "implementations": implementations,
        }
    ),
    "reference/parity.json": json_text(
        {
            "generatedBy": GENERATED_BY,
            "sourceVersion": upstream["version"],
            "statusDefinitions": STATUS_DEFINITIONS,
            "nodes": matrix,
            "edges": upstream["edges"],
            "views": [view["id"] for view in upstream["views"]],
        }
    ),
    "reference/PARITY.md": (
        "# Node coverage\n\n"
        "Every original ID is mapped. Status is implementation classification, not behavioral proof.\n\n"
        "| Node | Classification | Pi implementation |\n|---|---|---|\n"
        f"{rows}\n{MARKER}\n"
    ),
}
reconcile(outputs, args.check)
print(f"{len(outputs)} generated files, {len(steps)} playbooks, {len(matrix)} nodes")
