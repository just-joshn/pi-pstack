"""Generate the skills, playbooks and catalog from the upstream map.

Inputs:  reference/source-map.json (upstream graph, never edited)
         scripts/catalog-source.json (the instructions written for Pi)
Outputs: skills/**, lib/catalog-data.json, reference/parity.json, reference/PARITY.md

Run `python3 scripts/generate.py` to refresh owned outputs, or add `--check` to check them.
"""

import argparse
import json
import subprocess
from pathlib import Path
from tempfile import TemporaryDirectory

ROOT = Path(__file__).resolve().parents[1]
GENERATED_BY = "scripts/generate.py"
MARKER = (
    f"<!-- Generated by {GENERATED_BY} from scripts/catalog-source.json. "
    "Edit the source, then run `python3 scripts/generate.py`. -->"
)
RELATIONSHIPS = (
    "## Conditional relationships\n\n"
    "These are catalog references, not a mandatory call sequence. Read related instructions "
    "with `pstack_catalog` action `node` when the condition applies.\n\n"
)
PRINCIPLE_FOOTER = (
    "Read this leaf before applying it. In the final report, cite this principle only if it "
    "changed a specific decision and state that decision."
)
STATUS_DEFINITIONS = {
    "extension": "Executable Pi extension integration; live verification pending",
    "instruction": "Native skill or playbook; model-mediated, not deterministic",
    "host": "Provided by Pi",
    "conditional": "Requires project tool, external service, credentials, or workflow validation",
    "gap": "Managed service has no native equivalent",
    "navigation": "Native terminal catalog navigation",
}

upstream = json.loads((ROOT / "reference/source-map.json").read_text())
source = json.loads((ROOT / "scripts/catalog-source.json").read_text())
steps = source["steps"]


def is_skill(node):
    return node["kind"] == "public" or (
        node["id"].startswith("kit-") and node["label"].startswith("/")
    )


def classify(node):
    """Return (status, implementation, generated path, invocation) for one upstream node."""
    node_id = node["id"]
    if is_skill(node):
        name = node["label"].lstrip("/")
        path = f"skills/{name}/SKILL.md"
        if node_id in source["extensionSkills"]:
            status = "extension"
        elif node_id in source["conditionalSkills"]:
            status = "conditional"
        else:
            status = "instruction"
        command = "" if node_id.startswith("principle-") else f"; /{name}"
        return status, path + command, path, f"/skill:{name}"
    route = node_id.removeprefix("pb-")
    if node_id.startswith("pb-") and route in steps:
        path = f"skills/poteto-mode/playbooks/{route}.md"
        status = (
            "conditional" if route in source["conditionalPlaybooks"] else "instruction"
        )
        return status, f"{path} + pstack_plan", path, f"/pstack-run {route}"
    if "navigation group" in node["how"]:
        return "navigation", f"/pstack-map {node['opensView']}", None, None
    status, implementation = source["implementations"][node_id]
    return status, implementation, None, None


def frontmatter(name, description, manual_only=False):
    lines = ["---", f"name: {name}", f"description: {json.dumps(description)}"]
    if manual_only:
        lines.append("disable-model-invocation: true")
    return "\n".join([*lines, "---"])


def body(node):
    node_id = node["id"]
    if node_id.startswith("pb-"):
        route = node_id.removeprefix("pb-")
        ordered = "\n".join(f"{i}. {step}" for i, step in enumerate(steps[route], 1))
        return f"# {route}\n\nTrigger: {node['when']}\n\n## Ordered steps\n\n{ordered}"
    if node_id.startswith("principle-"):
        description = f"{node['what']} Apply when: {node['when']}."
        rule = source["principles"][node_id]
        return f"{frontmatter(node_id, description)}\n\n# {node_id}\n\n{rule}\n\n{PRINCIPLE_FOOTER}"
    name = node["label"].lstrip("/")
    description = f"{node['what']} Use when: {node['when']}"
    front = frontmatter(name, description, node_id in source["manualOnlySkills"])
    return f"{front}\n\n# {name}\n\n{source['skills'][node_id]}"


def relationships(node_id):
    links = [
        f"- `{edge['to']}`: {edge['label']}. {edge['when']}"
        for edge in upstream["edges"]
        if edge["from"] == node_id
    ]
    return RELATIONSHIPS + "\n".join(links) if links else ""


def json_text(value):
    return json.dumps(value, indent=2) + "\n"


def reconcile(outputs, check):
    stale = []
    with TemporaryDirectory(prefix="pstack-generate-") as tmp:
        stage = Path(tmp)
        for path, content in outputs.items():
            target = stage / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
        config = f"--config={ROOT / 'bunfig.toml'}"
        subprocess.run(
            ["bun", config, "fmt", "--log-level=warn", *outputs], cwd=stage, check=True
        )

        for path in outputs:
            expected = (stage / path).read_bytes()
            target = ROOT / path
            if target.is_file() and target.read_bytes() == expected:
                continue
            stale.append(path)
            if not check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(expected)

    for target in (ROOT / "skills").rglob("*.md"):
        path = target.relative_to(ROOT).as_posix()
        if path in outputs or target.is_symlink() or not target.is_file():
            continue
        if target.read_bytes().rstrip().endswith(MARKER.encode()):
            stale.append(path)
            if not check:
                target.unlink()
    if check and stale:
        raise SystemExit(
            "Stale generated files; run `python3 scripts/generate.py`:\n"
            + "\n".join(sorted(stale))
        )


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="check generated files without writing")
args = parser.parse_args()
outputs = {}
paths, implementations, matrix = dict(source["instructionPaths"]), {}, []
for node in upstream["nodes"]:
    status, implementation, path, invocation = classify(node)
    implementations[node["id"]] = (status, implementation)
    matrix.append(
        {
            "id": node["id"],
            "kind": node["kind"],
            "status": status,
            "implementation": implementation,
            "invocation": invocation,
            "source": node["source"],
        }
    )
    if path:
        paths[node["id"]] = path
        sections = [body(node), relationships(node["id"]), MARKER]
        outputs[path] = "\n\n".join(filter(None, sections)) + "\n"

outputs["lib/catalog-data.json"] = json_text(
    {
        "generatedBy": GENERATED_BY,
        "paths": paths,
        "steps": steps,
        "implementations": implementations,
    },
)
outputs["reference/parity.json"] = json_text(
    {
        "generatedBy": GENERATED_BY,
        "sourceVersion": upstream["version"],
        "statusDefinitions": STATUS_DEFINITIONS,
        "nodes": matrix,
        "edges": upstream["edges"],
        "views": [view["id"] for view in upstream["views"]],
    },
)
rows = "".join(
    f"| `{row['id']}` | {row['status']} | {row['implementation'].replace('|', ' or ')} |\n"
    for row in matrix
)
outputs["reference/PARITY.md"] = (
    "# Node coverage\n\n"
    "Every original ID is mapped. Status is implementation classification, not behavioral proof.\n\n"
    "| Node | Classification | Pi implementation |\n|---|---|---|\n"
    f"{rows}\n{MARKER}\n"
)
reconcile(outputs, args.check)
print(f"{len(outputs)} generated files, {len(steps)} playbooks, {len(matrix)} nodes")
