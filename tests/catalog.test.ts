import assert from "node:assert/strict";
import { access, readFile } from "node:fs/promises";
import { join } from "node:path";

import { test } from "vitest";

import {
	catalog,
	lookup,
	map,
	nativeNode,
	nodes,
	routes,
	srcDir,
	view,
	views,
	workflowPrompt,
} from "../src/lib/catalog.ts";
import { startPlan } from "../src/lib/state.ts";
import { assumeShape } from "./support.ts";

const packaged = (path: string) => readFile(join(srcDir, path), "utf8");
const parity = assumeShape<{ nodes: { id: string }[]; edges: unknown; views: unknown }>(
	JSON.parse(await packaged("reference/parity.json")),
);

test("all original nodes, edges and views are preserved and mapped", async () => {
	assert.equal(nodes.size, 162);
	assert.equal(map.edges.length, 163);
	assert.equal(views.size, 65);
	assert.equal(new Set(parity.nodes.map((n) => n.id)).size, 162);
	assert.deepEqual(parity.edges, map.edges);
	assert.deepEqual(
		parity.views,
		map.views.map((v) => v.id),
	);
	assert.deepEqual(new Set(parity.nodes.map((n) => n.id)), new Set(nodes.keys()));
	for (const e of map.edges) {
		assert(nodes.has(e.from));
		assert(nodes.has(e.to));
		assert((await nativeNode(e.from)).outgoing.some((x) => x.id === e.id));
		assert((await nativeNode(e.to)).incoming.some((x) => x.id === e.id));
	}
	for (const v of map.views) {
		const resolved = view(v.id);
		assert.equal(resolved.nodes.length, v.nodeIds.length);
		assert(resolved.edges.every(Boolean));
		if (v.parent) assert(views.has(v.parent));
	}
	assert.equal(view("all-dependencies").edges.length, 163);
});

test("77 native skills, 22 ordered playbooks and all conditional links", async () => {
	const skills = Object.entries(catalog.paths).filter(([, p]) => /^skills\/.*SKILL\.md$/.test(p));
	assert.equal(skills.length, 77);
	assert.equal(skills.filter(([id]) => id.startsWith("principle-")).length, 24);
	assert.equal(routes.length, 22);
	assert.equal(new Set(skills.map(([, p]) => p)).size, 77);
	await Promise.all(
		skills.map(async ([id, p]) => {
			const f = await packaged(p);
			const front = /^---\n([\s\S]*?)\n---\n/.exec(f)?.[1] ?? "";
			const name = /^name: ([a-z0-9-]+)$/m.exec(front)?.[1] ?? "";
			const description = /^description: (.+)$/m.exec(front)?.[1] ?? "";
			assert(name, id);
			assert.equal(name, p.split("/")[1]);
			assert(name.length <= 64);
			const described: unknown = description.startsWith('"') ? JSON.parse(description) : description;
			assert(typeof described === "string" && described.length <= 1024);
			assert(!f.includes("~/.cursor"));
		}),
	);
	for (const r of routes) {
		const n = await nativeNode("pb-" + r);
		const steps = catalog.steps[r] ?? [];
		assert(steps.length > 0, r);
		assert.deepEqual(
			startPlan(r, "goal").tasks.map((t) => t.text),
			steps,
		);
		if (!n.instructions?.includes("<!-- Generated by")) continue;
		assert(n.instructions.includes("## Ordered steps"));
		for (const e of n.outgoing) assert(n.instructions.includes("`" + e.to + "`"));
	}
	await Promise.all(Object.values(catalog.paths).map((p) => access(join(srcDir, p))));
});

test("catalog nodes return their declared instruction files, not display labels", async () => {
	const declared = {
		"benny-setup": "automations/benny/FOR_AGENTS.md",
		"benny-triage": "automations/benny/skills/triage-issue-reports/SKILL.md",
		"benny-repro": "automations/benny/skills/reproduce-and-fix-issues/SKILL.md",
		"benny-config": "automations/benny/templates/configuration.example.yaml",
		"kit-quality-agent": "agents/thermo-nuclear-code-quality-review.md",
		"kit-no-inline-imports": "reference/rules/no-inline-imports.md",
	};
	await Promise.all(
		Object.entries(declared).map(async ([id, path]) =>
			assert.equal((await nativeNode(id)).instructions, await packaged(path), id),
		),
	);
	assert.equal((await nativeNode("benny-slack")).instructions, undefined);
});

test("search and catalog reject missing references", async () => {
	assert(lookup("runtime diagnosis").some((n) => n.id === "pb-runtime-forensics"));
	assert.throws(() => view("unknown"));
	await assert.rejects(() => nativeNode("unknown"));
});

test("a workflow prompt names its file and both bases its relative paths use", async () => {
	const prompt = await workflowPrompt("poteto-mode", "fix it");
	const skill = join(srcDir, "skills/poteto-mode");
	assert(prompt.includes(`File: ${join(skill, "SKILL.md")}\n`));
	assert(prompt.endsWith("Operator request:\nfix it"));
	const playbook = await workflowPrompt("pb-babysit", "");
	const playbooks = join(skill, "playbooks");
	assert(playbook.includes(`File: ${join(playbooks, "babysit.md")}\n`));
	assert(playbook.includes(`A path starting with ../ resolves from ${playbooks}`));
	assert(playbook.includes(`other relative paths resolve from ${skill}`));
	await access(join(playbooks, "../references/bugbot-triage.md"));
	await access(join(skill, "playbooks/opening-a-pr.md"));
});

test("autopilot-stack's plan is autopilot-full's, with its two overrides applied", () => {
	const full = catalog.steps["autopilot-full"] ?? [];
	const stack = catalog.steps["autopilot-stack"] ?? [];
	assert.equal(full.length, 7);
	assert.deepEqual(stack, [
		full[0],
		full[1],
		`${full[2]} Exception: Stack a PR only when it builds on another PR.`,
		full[3],
		"In place of step 5, stop at verified.",
		full[5],
		full[6],
	]);
});
