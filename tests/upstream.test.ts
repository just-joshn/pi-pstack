import assert from "node:assert/strict";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join, relative } from "node:path";

import { test } from "vitest";

import { srcDir } from "../src/lib/catalog.ts";

const upstreamDir = join(srcDir, "..", "upstream");
const generated = "<!-- Generated by scripts/generate.py";

function markdown(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === "node_modules" ? [] : markdown(path);
    return entry.name.endsWith(".md") ? [path] : [];
  });
}

/** The upstream file that a hand-ported file under src/ translates. */
function upstreamOf(path: string) {
  const local = relative(srcDir, path);
  const candidates = ["pstack", "cursor-team-kit"].map((plugin) =>
    join(upstreamDir, plugin, local),
  );
  return candidates.find((candidate) => existsSync(candidate));
}

const ported = markdown(join(srcDir, "skills"))
  .filter((path) => !readFileSync(path, "utf8").includes(generated))
  .map((path) => ({ path, original: upstreamOf(path) }));

const headings = (text: string) => text.split("\n").filter((line) => /^#{1,6} /.test(line));
const steps = (text: string) => text.split("\n").filter((line) => /^\d+\. /.test(line)).length;
const name = (text: string) => /^---\nname: ([\w-]+)\n/.exec(text)?.[1];

test("every hand-ported file translates an upstream file", () => {
  assert(ported.length > 0);
  for (const { path, original } of ported)
    assert(original, `${relative(srcDir, path)} has no upstream counterpart`);
});

test("hand-ported files keep upstream's name, sections and numbered steps", () => {
  for (const { path, original } of ported) {
    if (!original) continue;
    const [pi, cursor] = [readFileSync(path, "utf8"), readFileSync(original, "utf8")];
    const label = relative(srcDir, path);
    assert.equal(name(pi), name(cursor), `${label}: name`);
    assert.deepEqual(headings(pi), headings(cursor), `${label}: headings`);
    assert.equal(steps(pi), steps(cursor), `${label}: numbered steps`);
  }
});

const cursorOnly = [
  /\.cursor\b/,
  /\.mdc\b/,
  /\bTask\b(?! list)/,
  /subagent_type/,
  /run_in_background/,
  /generalPurpose/,
  /cursor-team-kit/,
  /AskQuestion/,
  /-fast\b/,
  /\bCursor\b/,
];

test("hand-ported files name Pi mechanisms, not Cursor ones", () => {
  for (const { path } of ported) {
    const text = readFileSync(path, "utf8");
    for (const pattern of cursorOnly)
      assert.doesNotMatch(text, pattern, `${relative(srcDir, path)} still says ${pattern}`);
  }
});
